package oper03;

public class RelativeOp01 {

	public static void main(String[] args) {
		// 관계연산자 : <, <=, >, >=, == , !=
		// < : less than, > : greater than
		
		int  age  = 20;
		System.out.println( age < 19  );
		
		if( age < 19  ) {  // true
			System.out.println("미성년자");
		} else { // false
			System.out.println("성년");
		}

	}

}








